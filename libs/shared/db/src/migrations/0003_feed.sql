-- ============================================================================
--  0003_feed.sql — posts, likes and the materialised audience
--
--  The central problem this migration solves is that a timeline query must
--  answer "which posts may this viewer see?" without joining back to the follow
--  graph three times per row. Two mechanisms do that work:
--
--    1. `post_audience` records, at write time, exactly which follow edges a post
--       was addressed to. The home timeline is then one indexed join against the
--       viewer's own id, not a fan-in over every account they follow.
--    2. `can_view_post()` is a single SQL function that answers the visibility
--       question for one post. Every read path calls it, so a public endpoint
--       cannot accidentally invent its own, weaker rule.
--
--  Why the audience is materialised rather than computed per query: with a
--  `FOLLOWERS` audience the correct answer depends on follow state *at the time
--  the post was published*. Computing it later would silently reveal a post to
--  someone who followed after it was written, which the author did not consent
--  to. The rows are the record of that consent.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Posts.
--
-- `account_id` (the author) is the shard key. `id` is uuidv7, generated by the
-- application, so ids sort by creation time and the primary key doubles as the
-- timeline index — no separate `created_at` index on the hot path.
-- ---------------------------------------------------------------------------
CREATE TABLE posts (
  id           uuid PRIMARY KEY,
  account_id   uuid NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
  body         text NOT NULL,
  visibility   text NOT NULL DEFAULT 'PUBLIC',
  -- Reposts and replies are the same table with a pointer, not separate tables:
  -- a timeline is then a single scan, and a reply can be addressed with the same
  -- audience machinery as a post.
  repost_of    uuid REFERENCES posts (id) ON DELETE SET NULL,
  reply_to     uuid REFERENCES posts (id) ON DELETE CASCADE,
  like_count   integer NOT NULL DEFAULT 0,
  reply_count  integer NOT NULL DEFAULT 0,
  repost_count integer NOT NULL DEFAULT 0,
  edited_at    timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),

  -- 1..5000 characters after trimming. The empty check is separate from the
  -- length check so a blank post fails with a message that says so.
  CONSTRAINT posts_body_not_blank CHECK (btrim(body) <> ''),
  CONSTRAINT posts_body_len CHECK (char_length(body) <= 5000),
  CONSTRAINT posts_visibility_allowed CHECK (visibility IN ('PUBLIC', 'FOLLOWERS', 'PRIVATE')),
  CONSTRAINT posts_like_count_non_negative CHECK (like_count >= 0),
  CONSTRAINT posts_reply_count_non_negative CHECK (reply_count >= 0),
  CONSTRAINT posts_repost_count_non_negative CHECK (repost_count >= 0),
  -- A post cannot quote or reply to itself. The self-reference would make every
  -- recursive read ambiguous.
  CONSTRAINT posts_not_self_repost CHECK (repost_of IS NULL OR repost_of <> id),
  CONSTRAINT posts_not_self_reply CHECK (reply_to IS NULL OR reply_to <> id)
);

-- The home timeline: newest posts by author, used when a viewer follows few
-- accounts and the planner prefers a merge over the audience join.
CREATE INDEX posts_author_recent_idx ON posts (account_id, id DESC);
-- The public/discovery timeline and author profile pages.
CREATE INDEX posts_recent_idx ON posts (id DESC);
CREATE INDEX posts_reply_idx ON posts (reply_to, id) WHERE reply_to IS NOT NULL;

COMMENT ON TABLE posts IS
  'Posts, replies and reposts. Visibility is enforced by can_view_post(), not by callers.';

-- ---------------------------------------------------------------------------
-- Audience: one row per follow edge that was live when the post was published.
--
-- Purpose-built for the precomputed fan-out. A `FOLLOWERS` post writes one row
-- per current accepted follower; a `PUBLIC` post writes none, because it is
-- visible to everyone and materialising "everyone" is unbounded.
--
-- The composite primary key makes the fan-out idempotent, which matters because
-- it runs inside the same transaction as the post insert and may be retried.
-- ---------------------------------------------------------------------------
CREATE TABLE post_audience (
  post_id    uuid NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
  account_id uuid NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (post_id, account_id)
);

-- The home timeline reads this by viewer, newest first. `post_id` is uuidv7, so
-- ordering by it is ordering by publication time without a second column.
CREATE INDEX post_audience_viewer_idx ON post_audience (account_id, post_id DESC);

COMMENT ON TABLE post_audience IS
  'Materialised follower audience per post: the consent record for FOLLOWERS visibility.';

-- ---------------------------------------------------------------------------
-- Likes.
--
-- No counter column write outside the trigger below, and no surrogate key: the
-- pair *is* the like, so liking twice cannot inflate a count.
-- ---------------------------------------------------------------------------
CREATE TABLE post_likes (
  post_id    uuid NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
  account_id uuid NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (post_id, account_id)
);

CREATE INDEX post_likes_account_idx ON post_likes (account_id, post_id DESC);

-- ---------------------------------------------------------------------------
-- can_view_post(): the single definition of visibility.
--
-- Resolution order matters and is tested:
--   1. A block in either direction hides the post, even from a follower.
--   2. The author always sees their own posts.
--   3. PRIVATE is author-only.
--   4. PUBLIC is visible unless it is a reply to a post the viewer cannot see —
--      otherwise a reply to a private thread would leak that thread's existence
--      and, through the reply text, its content.
--   5. FOLLOWERS requires a live accepted follow.
--   6. Anything else (an unknown visibility, a null viewer) is denied by
--      default. A new visibility value therefore fails closed.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION can_view_post(post uuid, viewer uuid) RETURNS boolean
LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT CASE
    WHEN viewer IS NULL THEN false
    ELSE COALESCE(
      (
        SELECT CASE
          WHEN EXISTS (
            SELECT 1 FROM posts p
             WHERE p.id = can_view_post.post
               AND EXISTS (
                 SELECT 1 FROM blocks b
                  WHERE (b.blocker_id = can_view_post.viewer AND b.blocked_id = p.account_id)
                     OR (b.blocker_id = p.account_id AND b.blocked_id = can_view_post.viewer)
               )
          ) THEN false
          WHEN p.account_id = can_view_post.viewer THEN true
          WHEN p.visibility = 'PRIVATE' THEN false
          WHEN p.reply_to IS NOT NULL AND NOT can_view_post(p.reply_to, can_view_post.viewer) THEN false
          WHEN p.visibility = 'PUBLIC' THEN true
          WHEN p.visibility = 'FOLLOWERS' THEN EXISTS (
            SELECT 1 FROM follows f
             WHERE f.follower_id = can_view_post.viewer
               AND f.followee_id = p.account_id
               AND f.accepted_at IS NOT NULL
          )
          ELSE false
        END
        FROM posts p
        WHERE p.id = can_view_post.post
      ),
      -- No such post: not visible. Absence and denial are the same answer here,
      -- which is what keeps a deleted post from being distinguishable from a
      -- hidden one.
      false
    )
  END;
$$;

COMMENT ON FUNCTION can_view_post(uuid, uuid) IS
  'Sole authority on post visibility. Denies on block, PRIVATE, hidden parent replies and unknown visibility values.';

-- ---------------------------------------------------------------------------
-- Counters, maintained from the rows rather than by the application.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION maintain_like_count() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    UPDATE posts SET like_count = like_count + 1 WHERE id = NEW.post_id;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    UPDATE posts SET like_count = GREATEST(like_count - 1, 0) WHERE id = OLD.post_id;
    RETURN OLD;
  END IF;

  RETURN NULL;
END;
$$;

CREATE TRIGGER post_likes_maintain_count
  AFTER INSERT OR DELETE ON post_likes
  FOR EACH ROW EXECUTE FUNCTION maintain_like_count();

CREATE OR REPLACE FUNCTION maintain_reply_count() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' AND NEW.reply_to IS NOT NULL THEN
    UPDATE posts SET reply_count = reply_count + 1 WHERE id = NEW.reply_to;
  ELSIF TG_OP = 'DELETE' AND OLD.reply_to IS NOT NULL THEN
    UPDATE posts SET reply_count = GREATEST(reply_count - 1, 0) WHERE id = OLD.reply_to;
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER posts_maintain_reply_count
  AFTER INSERT OR DELETE ON posts
  FOR EACH ROW EXECUTE FUNCTION maintain_reply_count();

CREATE OR REPLACE FUNCTION maintain_repost_count() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' AND NEW.repost_of IS NOT NULL THEN
    UPDATE posts SET repost_count = repost_count + 1 WHERE id = NEW.repost_of;
  ELSIF TG_OP = 'DELETE' AND OLD.repost_of IS NOT NULL THEN
    UPDATE posts SET repost_count = GREATEST(repost_count - 1, 0) WHERE id = OLD.repost_of;
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER posts_maintain_repost_count
  AFTER INSERT OR DELETE ON posts
  FOR EACH ROW EXECUTE FUNCTION maintain_repost_count();

